"""Music analysis -> data/audio.json

  * constant-tempo beat grid (tempo + phase fitted to drum / mix onsets, phase
    refined on kick attacks), downbeats (bar phase from snare-on-2&4 and the
    lyric phrases starting on bars), sections on downbeats,
  * 100 fps normalized envelopes (mix rms / low / mid / high, stem rms),
  * kick / snare / hat onsets from the drums stem, vocal note onsets.

All times are on the audio/song.wav timeline (the album version; Demucs stems from stems.py).
The beat grid starts 9 beats before the song (at -3.26 s): the TV cut's first downbeat, so bar and
beat numbers are the TV cut's (and the docs'): bar k = the TV cut's bar k, 3.36 s earlier.

Run:  uv run python analyze.py [--plots]
"""
import common
import json
import math
import sys

import numpy as np
import librosa
from scipy.ndimage import maximum_filter1d, median_filter, uniform_filter1d
from scipy.signal import butter, find_peaks, sosfiltfilt

SR = 44100
FPS = 100

BPM_RANGE = (150.0, 175.0)  # tempogram peaks 80.7 / 107.7 / 161.5: one tempo at 1/2, 2/3 and 1x
BAR_PHASE = 0               # index of the first grid beat that is a downbeat (0..3), from the snare positions
BEATS_BEFORE = 9            # grid beats before t = 0 (the TV cut's pre-roll: its bar 0 is at -3.26 s here)

# Section map in bars (bar k starts at downbeat k; bar 0 is at -3.26 s, see BEATS_BEFORE). The lyric
# lines are 4-bar phrases: the verse lines start on bars 12/16/20/24 (L1, L3 with 2-beat pickups), the
# pre-chorus lines on 28/32/36/40 (pickups), "Hacking to the Gate" from a 1.25-beat pickup into bar
# 43, the chorus lines on 44/48/52/56. Verse 2 to chorus 2 repeat that form 60 bars later; the final
# chorus starts 104 bars after the first. A section starts on the downbeat of its first line's bar, or
# of the next bar when the line starts with a pickup (< 2 beats).
SECTION_BARS = [
    ("intro", None, 12),
    ("verse", 12, 28),      # A-melo, L0-L3
    ("pre", 28, 43),        # B-melo, L4-L7
    ("hook", 43, 44),       # "Hacking to the Gate"
    ("chorus", 44, 61),     # sabi, L9-L12. Bar 44 is a break (bass out) under だからいま; full band from 45;
                            # the held 観測者 runs to bar 61
    ("interlude", 61, 72),  # instrumental
    ("verse2", 72, 88),     # L13-L16
    ("pre2", 88, 103),      # L17-L20
    ("hook2", 103, 104),    # "Hacking to the Gate" (L21)
    ("chorus2", 104, 121),  # L22-L25; bar 104 is a break under いくつもの
    ("solo", 121, 146),     # guitar solo
    ("break", 146, 148),    # bass out
    ("chorus3", 148, 165),  # L26-L29 (the first chorus's lines); だからいま over no bass, full band from 149
    ("outro", 165, None),   # fades out by ~250 s
]


# ---------------------------------------------------------------------------
def band_sos(lo, hi, sr):
    if lo and hi:
        return butter(4, [lo, hi], btype="band", fs=sr, output="sos")
    if hi:
        return butter(4, hi, btype="low", fs=sr, output="sos")
    return butter(4, lo, btype="high", fs=sr, output="sos")


def frame_rms(x, sr, fps=FPS, win=2048):
    hop = sr / fps
    n = int(math.ceil(len(x) / sr * fps))
    pad = np.pad(x, (win // 2, win // 2 + int(hop) + 2))
    idx = (np.arange(n) * hop).astype(int)
    c = np.concatenate([[0.0], np.cumsum(pad.astype(np.float64) ** 2)])
    e = (c[idx + win] - c[idx]) / win
    return np.sqrt(np.maximum(e, 0))


def smooth_env(x, fps=FPS, attack=0.010, release=0.090):
    """One-pole follower: fast attack, slower release (visual friendly)."""
    aa = math.exp(-1 / (attack * fps))
    ar = math.exp(-1 / (release * fps))
    y = np.empty_like(x)
    s = 0.0
    for i, v in enumerate(x):
        a = aa if v > s else ar
        s = a * s + (1 - a) * v
        y[i] = s
    return y


def norm01(x, pct=99.0):
    ref = np.percentile(x, pct)
    return np.clip(x / (ref + 1e-12), 0, 1)


